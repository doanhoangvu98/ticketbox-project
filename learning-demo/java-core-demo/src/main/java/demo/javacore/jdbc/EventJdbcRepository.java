package demo.javacore.jdbc;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Plain JDBC, no framework: what Spring's JdbcTemplate does for us in ticketbox-api.
 *
 * <ul>
 *   <li>DriverManager opens a Connection from a JDBC URL. The driver (PostgreSQL, H2, ...) registers
 *       itself automatically when it is on the classpath, so no Class.forName is needed.</li>
 *   <li>PreparedStatement with "?" placeholders: values travel separately from the SQL text,
 *       so user input can never change the query (no SQL injection).</li>
 *   <li>ResultSet: a cursor over the result rows, read column by column.</li>
 *   <li>try-with-resources closes ResultSet, Statement and Connection, in reverse order.</li>
 *   <li>Transaction: setAutoCommit(false) + commit/rollback makes several inserts all-or-nothing.</li>
 * </ul>
 *
 * <p>Table name "demo_event" so it never clashes with the real "event" table of ticketbox-api.
 */
public class EventJdbcRepository {

    private static final String INSERT_SQL = "INSERT INTO demo_event (name, base_price) VALUES (?, ?)";

    private final String url;
    private final String user;
    private final String password;

    public EventJdbcRepository(String url, String user, String password) {
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /** Input of {@link #insertAll}: an event that has no id yet. */
    public record NewEvent(String name, BigDecimal basePrice) {
    }

    public void createTable() {
        String sql = """
                CREATE TABLE IF NOT EXISTS demo_event (
                    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name       VARCHAR(200)   NOT NULL,
                    base_price NUMERIC(12, 0) NOT NULL CHECK (base_price > 0)
                )
                """;
        try (Connection connection = connect();
             Statement statement = connection.createStatement()) {
            statement.execute(sql);
        } catch (SQLException e) {
            throw new JdbcException("Could not create table demo_event", e);
        }
    }

    /** Inserts one row and returns the id generated by the database. */
    public long insert(String name, BigDecimal basePrice) {
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(INSERT_SQL, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, name);          // parameters are numbered from 1
            statement.setBigDecimal(2, basePrice);
            statement.executeUpdate();
            try (ResultSet keys = statement.getGeneratedKeys()) {
                keys.next();
                return keys.getLong(1);
            }
        } catch (SQLException e) {
            throw new JdbcException("Could not insert event '" + name + "'", e);
        }
    }

    public Optional<EventRow> findById(long id) {
        String sql = "SELECT id, name, base_price FROM demo_event WHERE id = ?";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            try (ResultSet rows = statement.executeQuery()) {
                return rows.next() ? Optional.of(toRow(rows)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw new JdbcException("Could not load event " + id, e);
        }
    }

    /** Case-insensitive search. The keyword is a parameter, never concatenated into the SQL. */
    public List<EventRow> findByNameContaining(String keyword) {
        String sql = "SELECT id, name, base_price FROM demo_event WHERE LOWER(name) LIKE ? ORDER BY id";
        try (Connection connection = connect();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, "%" + keyword.toLowerCase() + "%");
            try (ResultSet rows = statement.executeQuery()) {
                List<EventRow> events = new ArrayList<>();
                while (rows.next()) { // moves the cursor to the next row; false when there are no more
                    events.add(toRow(rows));
                }
                return events;
            }
        } catch (SQLException e) {
            throw new JdbcException("Could not search events", e);
        }
    }

    /**
     * Inserts all events or none of them.
     * If one row fails (e.g. a null name), rollback() undoes the rows already inserted in this transaction.
     */
    public void insertAll(List<NewEvent> events) {
        try (Connection connection = connect()) {
            connection.setAutoCommit(false); // start a transaction: nothing is permanent until commit()
            try (PreparedStatement statement = connection.prepareStatement(INSERT_SQL)) {
                for (NewEvent event : events) {
                    statement.setString(1, event.name());
                    statement.setBigDecimal(2, event.basePrice());
                    statement.addBatch(); // queued, then sent to the database in one round-trip
                }
                statement.executeBatch();
                connection.commit();
            } catch (SQLException e) {
                connection.rollback(); // undo everything done in this transaction
                throw e;
            }
        } catch (SQLException e) {
            throw new JdbcException("Could not insert events, nothing was saved", e);
        }
    }

    public int count() {
        try (Connection connection = connect();
             Statement statement = connection.createStatement();
             ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM demo_event")) {
            rows.next();
            return rows.getInt(1);
        } catch (SQLException e) {
            throw new JdbcException("Could not count events", e);
        }
    }

    private Connection connect() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    private static EventRow toRow(ResultSet rows) throws SQLException {
        return new EventRow(rows.getLong("id"), rows.getString("name"), rows.getBigDecimal("base_price"));
    }
}
